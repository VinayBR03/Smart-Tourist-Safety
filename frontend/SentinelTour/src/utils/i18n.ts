// Normalise to lowercase so "EN", "En", "en" all work
export function normaliseLanguage(lang: string | null | undefined): UserLanguage {
  if (!lang) return 'en';
  const lower = lang.toLowerCase();
  const valid: UserLanguage[] = ['en', 'hi', 'kn', 'te', 'ta', 'ml'];
  return valid.includes(lower as UserLanguage) ? (lower as UserLanguage) : 'en';
}

